CATALOGUES: Final[dict[str, dict[str, str]]] = {
    "en": EN,
    "de": DE,
    "fr": FR,
    "nl": NL,
    "it": IT,
    "es": ES,
    "pt": PT,
    "pl": PL,
    "sv": SV,
    "da": DA,
    "cs": CS,
}


def normalise(language: str | None) -> str:
    """Return a language we have a catalogue for.

    Home Assistant hands out regional codes like ``de-CH``; those fall back to
    their base language, and anything unknown falls back to English.
    """
    if not language:
        return DEFAULT_LANGUAGE
    code = language.replace("_", "-").split("-")[0].lower()
    return code if code in CATALOGUES else DEFAULT_LANGUAGE


def translate(language: str, key: str, **params: Any) -> str:
    """Return one translated text, falling back to English key by key."""
    catalogue = CATALOGUES.get(normalise(language), EN)
    template = catalogue.get(key) or EN.get(key)
    if template is None:
        return key
    try:
        return template.format(**params)
    except (KeyError, IndexError):
        return template


def finding_text(language: str, rule_id: str, params: dict[str, Any]) -> str:
    """Return the sentence for one finding."""
    key = f"rule.{rule_id}"
    if rule_id == "unpinned":
        key = "rule.unpinned.branch" if "branch" in params else "rule.unpinned.commit"
    return translate(language, key, **params)
